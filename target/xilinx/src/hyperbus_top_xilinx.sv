`include "axi/typedef.svh"
`include "register_interface/typedef.svh"

module hyperbus_top_xilinx
(
  input logic       sys_clk_p,
  input logic       sys_clk_n,

  input logic       cpu_reset,
  
  inout  [1:0][1:0] pad_hyper_csn,
  inout  [1:0]      pad_hyper_ck,
  inout  [1:0]      pad_hyper_ckn,
  inout  [1:0]      pad_hyper_rwds,
  inout  [1:0]      pad_hyper_reset,
  inout  [1:0][7:0] pad_hyper_dq
);

  logic hyp_clk;
  logic clk_100, clk_200, clk_20;
  logic sys_clk, sys_rst;
  
  (* dont_touch = "yes" *) logic rst_n;

  logic vio_reset;

  xlnx_vio (
    .clk(soc_clk),
    .probe_out0(vio_reset)
  );

  clk_wiz_0 i_xlnx_clk_wiz (
    .clk_in1_n ( sys_clk_n  ),
    .clk_in1_p ( sys_clk_p  ),
    .reset     ( '0         ),
    .hype_clk  ( hyp_clk    ),
    .clk_100   ( clk_100    ),
    .clk_200   ( clk_200    )
  );
  
  assign sys_rst = cpu_reset | vio_reset;
  assign soc_clk = clk_100;
 

  rstgen i_rstgen_main (
    .clk_i        ( soc_clk                  ),
    .rst_ni       ( ~sys_rst                 ),
    .test_mode_i  ( 1'b0                     ),
    .rst_no       ( rst_n                    ),
    .init_no      (                          ) // keep open
  );

  // Used for the axi interface
  localparam int unsigned AddrWidth = 32;
  localparam int unsigned AxiDataWidth = 64;
  
  // Used for the registers
  localparam int unsigned AxiNarrowAddrWidth = 32;
  localparam int unsigned AxiNarrowDataWidth = 32;
  
  // Used for the axi crossbar
  localparam int unsigned AxiIdWidth = 1;
  localparam int unsigned AxiUserWidth = 32;
  localparam int unsigned SlaveArWidth = 32;
  localparam int unsigned SlaveAwWidth = 32;
  localparam int unsigned SlaveBWidth = 32;
  localparam int unsigned SlaveRWidth = 32;
  localparam int unsigned SlaveWWidth = 32;
  localparam int unsigned LogDepth = 32;
  localparam int unsigned AxiMaxSlvTrans = 32;
  localparam int unsigned SyncStages = 32;

  // Used for Hyperbus
  localparam int unsigned NumChips = 2;
  localparam int unsigned NumPhys = 2;
  
  
   // AXI interface for the hyperram (64bit datawidth)
  `AXI_TYPEDEF_ALL_CT(axi, axi_req_t, axi_rsp_t, logic[AddrWidth-1:0], logic[AxiIdWidth-1:0], logic[AxiDataWidth-1:0], logic[AxiDataWidth/8-1:0], logic[AxiUserWidth-1:0])
   // AXI interface for the hyperbus registers (32bit datawidth)
  `AXI_TYPEDEF_ALL_CT(axi_reg, axi_reg_req_t, axi_reg_rsp_t, logic[AddrWidth-1:0], logic[AxiIdWidth-1:0], logic[AxiNarrowDataWidth-1:0], logic[AxiNarrowDataWidth/8-1:0], logic[AxiUserWidth-1:0])
 
  `REG_BUS_TYPEDEF_ALL(hyper_reg, logic [31:0], logic [31:0], logic [3:0])


/*
  It is not possible to set the w strobe field of the axi transaction generated by the Jtag-to-Axi IP. For this reason, and to have a cleaner design
  we use two instances of the same IP, one with datawith of 32bit (hyperbus regs) and 64bit (hyperram).

  The Jtag-to-AXI IP supports queued transaction to increase bw and reduce latency. 
*/

  jtag_axi_64 i_jtag_to_axi_mem (
    .aclk           (hyp_clk),
    .aresetn        (rst_n),

    .m_axi_awid     (axi_mem_req.aw.id),
    .m_axi_awaddr   (axi_mem_req.aw.addr),
    .m_axi_awlen    (axi_mem_req.aw.len),
    .m_axi_awsize   (axi_mem_req.aw.size),
    .m_axi_awburst  (axi_mem_req.aw.burst),
    .m_axi_awlock   (axi_mem_req.aw.lock),
    .m_axi_awcache  (axi_mem_req.aw.cache),
    .m_axi_awprot   (axi_mem_req.aw.prot),
    .m_axi_awqos    (axi_mem_req.aw.qos),
    .m_axi_awvalid  (axi_mem_req.aw_valid),
    .m_axi_awready  (axi_mem_rsp.aw_ready),

    .m_axi_wdata    (axi_mem_req.w.data),
    .m_axi_wstrb    (axi_mem_req.w.strb),
    .m_axi_wlast    (axi_mem_req.w.last),
    .m_axi_wvalid   (axi_mem_req.w_valid),
    .m_axi_wready   (axi_mem_rsp.w_ready),

    .m_axi_bid      (axi_mem_rsp.b.id),
    .m_axi_bresp    (axi_mem_rsp.b.resp),
    .m_axi_bvalid   (axi_mem_rsp.b_valid),
    .m_axi_bready   (axi_mem_req.b_ready),

    .m_axi_arid     (axi_mem_req.ar.id),
    .m_axi_araddr   (axi_mem_req.ar.addr),
    .m_axi_arlen    (axi_mem_req.ar.len),
    .m_axi_arsize   (axi_mem_req.ar.size),
    .m_axi_arburst  (axi_mem_req.ar.burst),
    .m_axi_arlock   (axi_mem_req.ar.lock),
    .m_axi_arcache  (axi_mem_req.ar.cache),
    .m_axi_arprot   (axi_mem_req.ar.prot),
    .m_axi_arqos    (axi_mem_req.ar.qos),
    .m_axi_arvalid  (axi_mem_req.ar_valid),
    .m_axi_arready  (axi_mem_rsp.ar_ready),

    .m_axi_rid      (axi_mem_rsp.r.id),
    .m_axi_rdata    (axi_mem_rsp.r.data),
    .m_axi_rresp    (axi_mem_rsp.r.resp),
    .m_axi_rlast    (axi_mem_rsp.r.last),
    .m_axi_rvalid   (axi_mem_rsp.r_valid),
    .m_axi_rready   (axi_mem_req.r_ready)
  );
  
  
  
    jtag_axi_32 i_jtag_to_axi_reg (
    .aclk           (hyp_clk),
    .aresetn        (rst_n),

    .m_axi_awid     (axi_reg_req.aw.id),
    .m_axi_awaddr   (axi_reg_req.aw.addr),
    .m_axi_awlen    (axi_reg_req.aw.len),
    .m_axi_awsize   (axi_reg_req.aw.size),
    .m_axi_awburst  (axi_reg_req.aw.burst),
    .m_axi_awlock   (axi_reg_req.aw.lock),
    .m_axi_awcache  (axi_reg_req.aw.cache),
    .m_axi_awprot   (axi_reg_req.aw.prot),
    .m_axi_awqos    (axi_reg_req.aw.qos),
    .m_axi_awvalid  (axi_reg_req.aw_valid),
    .m_axi_awready  (axi_reg_rsp.aw_ready),

    .m_axi_wdata    (axi_reg_req.w.data),
    .m_axi_wstrb    (axi_reg_req.w.strb),
    .m_axi_wlast    (axi_reg_req.w.last),
    .m_axi_wvalid   (axi_reg_req.w_valid),
    .m_axi_wready   (axi_reg_rsp.w_ready),

    .m_axi_bid      (axi_reg_rsp.b.id),
    .m_axi_bresp    (axi_reg_rsp.b.resp),
    .m_axi_bvalid   (axi_reg_rsp.b_valid),
    .m_axi_bready   (axi_reg_req.b_ready),

    .m_axi_arid     (axi_reg_req.ar.id),
    .m_axi_araddr   (axi_reg_req.ar.addr),
    .m_axi_arlen    (axi_reg_req.ar.len),
    .m_axi_arsize   (axi_reg_req.ar.size),
    .m_axi_arburst  (axi_reg_req.ar.burst),
    .m_axi_arlock   (axi_reg_req.ar.lock),
    .m_axi_arcache  (axi_reg_req.ar.cache),
    .m_axi_arprot   (axi_reg_req.ar.prot),
    .m_axi_arqos    (axi_reg_req.ar.qos),
    .m_axi_arvalid  (axi_reg_req.ar_valid),
    .m_axi_arready  (axi_reg_rsp.ar_ready),

    .m_axi_rid      (axi_reg_rsp.r.id),
    .m_axi_rdata    (axi_reg_rsp.r.data),
    .m_axi_rresp    (axi_reg_rsp.r.resp),
    .m_axi_rlast    (axi_reg_rsp.r.last),
    .m_axi_rvalid   (axi_reg_rsp.r_valid),
    .m_axi_rready   (axi_reg_req.r_ready)
  );


  logic[31:0] tx_timer;
  (* mark_debug = "true" *) logic[31:0] ila_tx_timer;


  always_ff @(posedge hyp_clk or negedge rst_n) begin
      if (~rst_n) begin
          tx_timer  <= '0;
          ila_tx_timer  <= '0;
      end else begin
        
        if (axi_mem_req.aw_valid) begin
          tx_timer  <= '0;
        end else if (!axi_mem_req.w.last) begin
          tx_timer  <= tx_timer + 1;
        end

        if (axi_mem_req.w.last) begin
          ila_tx_timer <= tx_timer;
        end
      end
  end

  
  (* mark_debug = "true" *) axi_req_t   axi_mem_req;
  (* mark_debug = "true" *) axi_rsp_t   axi_mem_rsp;
  (* mark_debug = "true" *) axi_reg_req_t   axi_reg_req;
  (* mark_debug = "true" *) axi_reg_rsp_t   axi_reg_rsp;


hyperbus_wrap      #(
  .NumChips             ( NumChips                            ),
  .NumPhys              ( NumPhys                             ),
  .AxiAddrWidth         ( AddrWidth                           ),
  .AxiDataWidth         ( AxiDataWidth                        ),
  .AxiIdWidth           ( AxiIdWidth                          ),
  .AxiUserWidth         ( AxiUserWidth                        ),
  .axi_req_t            ( axi_req_t                           ),
  .axi_rsp_t            ( axi_rsp_t                           ),
  .axi_reg_req_t        ( axi_reg_req_t                       ),
  .axi_reg_rsp_t        ( axi_reg_rsp_t                       ),
  .RegAddrWidth         ( AxiNarrowAddrWidth                  ),
  .RegDataWidth         ( AxiNarrowDataWidth                  ),
  .reg_req_t            ( hyper_reg_req_t                     ),
  .reg_rsp_t            ( hyper_reg_rsp_t                     ),
  .axi_aw_chan_t        ( axi_aw_chan_t                       ),
  .axi_w_chan_t         ( axi_w_chan_t                        ),
  .axi_b_chan_t         ( axi_b_chan_t                        ),
  .axi_ar_chan_t        ( axi_ar_chan_t                       ),
  .axi_r_chan_t         ( axi_r_chan_t                        ),
  .axi_reg_aw_chan_t    ( axi_reg_aw_chan_t                   ),
  .axi_reg_w_chan_t     ( axi_reg_w_chan_t                    ),
  .axi_reg_b_chan_t     ( axi_reg_b_chan_t                    ),
  .axi_reg_ar_chan_t    ( axi_reg_ar_chan_t                   ),
  .axi_reg_r_chan_t     ( axi_reg_r_chan_t                    ),
  .RxFifoLogDepth       ( 32'd2                               ),
  .TxFifoLogDepth       ( 32'd2                               ),
  .RstChipBase          ( 'h0                                 ),
  .RstChipSpace         ( NumChips * NumPhys * 'h800_0000     ),
  .PhyStartupCycles     ( 300 * 200                           ),
  .AxiLogDepth          ( LogDepth                            ),
  .AxiSlaveArWidth      ( SlaveArWidth                        ),
  .AxiSlaveAwWidth      ( SlaveAwWidth                        ),
  .AxiSlaveBWidth       ( SlaveBWidth                         ),
  .AxiSlaveRWidth       ( SlaveRWidth                         ),
  .AxiSlaveWWidth       ( SlaveWWidth                         ),
  .AxiMaxTrans          ( AxiMaxSlvTrans                      ),
  .CdcSyncStages        ( SyncStages                          )
) i_hyperbus_wrap   (
  .clk_i               ( hyp_clk           ),
  .rst_ni              ( rst_n             ),
  .test_mode_i         ( 1'b0              ),
  .axi_reg_req         ( axi_reg_req       ),
  .axi_reg_rsp         ( axi_reg_rsp       ),
  .hyper_req           ( axi_mem_req       ),
  .hyper_rsp           ( axi_mem_rsp       ),
  // Reference clock for the IDELAY Xilinx primitive
  .clk_ref200_i(clk_200),
  // Hyperbus pinout
  .pad_hyper_csn,
  .pad_hyper_ck,
  .pad_hyper_ckn,
  .pad_hyper_rwds,
  .pad_hyper_dq,
  .pad_hyper_reset
);


endmodule
